"""
Optional AI Provider Integration Client
Supports server-side API key handling for providers like Google Gemini or OpenAI.
Defaults transparently to the rule-based heuristic engine when no API key is configured.
Never claims live AI is running unless an external AI provider successfully analyzes the input.
"""

import os
import json
import logging
from typing import Dict, Any, Optional
import requests
from .rule_engine import PhishingRuleEngine

logger = logging.getLogger(__name__)


class MessageAnalyzerService:
    def __init__(self):
        self.rule_engine = PhishingRuleEngine()
        self.ai_provider = os.getenv("AI_PROVIDER", "none").strip().lower()
        self.gemini_api_key = os.getenv("GEMINI_API_KEY", "").strip()
        self.openai_api_key = os.getenv("OPENAI_API_KEY", "").strip()

    def get_status(self) -> Dict[str, Any]:
        """Returns the current operational status of the analyzer."""
        if self.ai_provider == "gemini" and self.gemini_api_key:
            active_engine = "Google Gemini AI (Live API)"
            mode = "live_ai"
        elif self.ai_provider == "openai" and self.openai_api_key:
            active_engine = "OpenAI API (Live API)"
            mode = "live_ai"
        else:
            active_engine = "Transparent Heuristic Rule-Based Engine (Demo Mode)"
            mode = "demo_heuristic"

        return {
            "mode": mode,
            "engine_name": active_engine,
            "is_live_ai_configured": mode == "live_ai",
            "provider": self.ai_provider if mode == "live_ai" else "none (rule_engine)",
            "message": "System operating in transparent offline-ready demo mode. Paid APIs are not required for demonstration." if mode == "demo_heuristic" else "Connected to external AI service."
        }

    def analyze(self, text: str, sender: str = "") -> Dict[str, Any]:
        """
        Analyzes message text. Uses configured AI provider if available,
        otherwise safely routes through the transparent heuristic rule engine.
        """
        # If live AI is configured, attempt analysis
        if self.ai_provider == "gemini" and self.gemini_api_key:
            result = self._analyze_with_gemini(text, sender)
            if result:
                return result

        elif self.ai_provider == "openai" and self.openai_api_key:
            result = self._analyze_with_openai(text, sender)
            if result:
                return result

        # Default fallback: Transparent Heuristic Rule Engine
        result = self.rule_engine.analyze(text, sender_header=sender)
        return result

    def _analyze_with_gemini(self, text: str, sender: str) -> Optional[Dict[str, Any]]:
        """Call Gemini REST endpoint securely server-side."""
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={self.gemini_api_key}"
            prompt = self._build_llm_prompt(text, sender)
            
            payload = {
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {
                    "temperature": 0.2,
                    "responseMimeType": "application/json"
                }
            }
            
            resp = requests.post(url, json=payload, timeout=8)
            if resp.status_code == 200:
                data = resp.json()
                raw_text = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(raw_text)
                parsed["assessment_type"] = "Google Gemini 1.5 Flash (Live Server-Side AI)"
                parsed["engine_mode"] = "live_ai"
                parsed["disclaimer"] = "Educational Advisory Notice: This classification was generated by an external AI model. AI systems can produce false positives or false negatives. Always verify unexpected communications using out-of-band institutional channels."
                return parsed
        except Exception as e:
            logger.warning(f"Gemini API call failed: {e}. Falling back to Rule Engine.")
        return None

    def _analyze_with_openai(self, text: str, sender: str) -> Optional[Dict[str, Any]]:
        """Call OpenAI REST endpoint securely server-side."""
        try:
            url = "https://api.openai.com/v1/chat/completions"
            prompt = self._build_llm_prompt(text, sender)
            headers = {
                "Authorization": f"Bearer {self.openai_api_key}",
                "Content-Type": "application/json"
            }
            payload = {
                "model": "gpt-4o-mini",
                "messages": [
                    {"role": "system", "content": "You are a cybersecurity phishing awareness analyzer. Output strictly valid JSON."},
                    {"role": "user", "content": prompt}
                ],
                "temperature": 0.2,
                "response_format": {"type": "json_object"}
            }
            resp = requests.post(url, headers=headers, json=payload, timeout=8)
            if resp.status_code == 200:
                data = resp.json()
                raw_text = data["choices"][0]["message"]["content"]
                parsed = json.loads(raw_text)
                parsed["assessment_type"] = "OpenAI GPT-4o-mini (Live Server-Side AI)"
                parsed["engine_mode"] = "live_ai"
                parsed["disclaimer"] = "Educational Advisory Notice: This classification was generated by an external AI model. AI systems can produce false positives or false negatives. Always verify unexpected communications using out-of-band institutional channels."
                return parsed
        except Exception as e:
            logger.warning(f"OpenAI API call failed: {e}. Falling back to Rule Engine.")
        return None

    def _build_llm_prompt(self, text: str, sender: str) -> str:
        return f"""
Analyze the following email or message for cybersecurity phishing indicators.
Classification must strictly be one of:
1. "Likely phishing"
2. "Suspicious — needs verification"
3. "Likely legitimate"

Sender: {sender or 'Not provided'}
Message Body:
\"\"\"{text}\"\"\"

Return strictly a JSON object with this schema:
{{
  "classification": "Likely phishing" | "Suspicious — needs verification" | "Likely legitimate",
  "risk_level": "High" | "Medium" | "Low",
  "score": integer (0 to 100),
  "qualitative_assessment": "Short 1-line summary of risk",
  "confidence_score": "String e.g. '88% Model Confidence'",
  "indicators": [
    {{
      "name": "Indicator name",
      "category": "Category",
      "severity": "High" | "Medium" | "Low",
      "matches": ["matched snippet or keyword"],
      "explanation": "Why this indicator matters"
    }}
  ],
  "positive_indicators": [
    {{
      "name": "Signal name",
      "matches": ["matched phrase"],
      "explanation": "Why this signal suggests legitimacy"
    }}
  ],
  "safe_actions": [
    "Recommended safe step 1",
    "Recommended safe step 2"
  ]
}}
"""

